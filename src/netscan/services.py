def service_for(port: int) -> ServiceInfo:
    """Look up a port, returning a synthetic entry for anything not catalogued."""
    known = SERVICES.get(port)
    if known is not None:
        return known
    return ServiceInfo(name="unknown", description="Unassigned or application-specific port")


def resolve_preset(name: str) -> Tuple[int, ...]:
    """Expand a named preset to a tuple of ports, or raise ``KeyError``."""
    key = name.strip().lower()
    if key in PRESETS:
        return PRESETS[key]
    raise KeyError(f"unknown port profile {name!r}; known: {', '.join(sorted(PRESETS))}")


def all_ports() -> List[int]:
    """Every catalogued port, ascending. Useful for ``--profile all``."""
    return sorted(SERVICES)
